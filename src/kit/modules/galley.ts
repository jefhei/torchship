/**
 * M2-T3 — the authored GALLEY / BUNK module: the crew's heart.
 *
 * PRD §4 landmark: "The galley/bunk: the mess table and the coffee station —
 * the crew's heart — plus berths and the head." The room is one deck module on
 * the M1-T2 authoring frame — floor at local y = 0, footprint centred on the
 * origin in XZ, the standardized `spine-door` flush in the module's −z face at
 * the standard 1.0 m centre (src/fixtures/layout.ts: every room attaches to
 * the spine's +z face, so the −z face is the centreline breach to the shaft).
 *
 * Reading the room from the spine door (aft, −z) toward the bow (+z):
 *  - the walkway runs straight up the centreline past the berth stack;
 *  - the BERTHS (two high) are stacked on the port wall aft — the bunk alcove;
 *  - the MESS (bolted table + two benches facing it) fills the starboard side;
 *  - the PANTRY locker bank lines the port wall amidships;
 *  - the COFFEE STATION — the §4 warm-accent landmark with the room's one
 *    reserved warm material — is centred on the forward wall, facing the
 *    spine door: it is what you see walking in, and it is deliberately the
 *    only coffee-accent geometry in the module;
 *  - the HEAD (toilet/shower) is a partition-built stall in the forward-port
 *    corner, entered through a 0.7 × 1.9 m doorway in its aft partition.
 *
 * The starboard wall carries the contract's `side-door` socket (M1-T3
 * contractKit) — a door off-centre along the wall, so the wall panel is cut
 * with the bulkhead builder's `door.centerX` (never freehand geometry,
 * BUILD_PLAN rule 8) and the opening is sealed with a socket-centred hatch the
 * same way the spine door is. Both hatches belong to the room; the M2-T6 spine
 * module supplies the shaft + per-deck sockets and adds NO hatch of its own.
 *
 * Everything is generated by the M2-T1 builders and placed through
 * `placePart` / `placePoint`; `GALLEY_ASSEMBLIES` is the authored truth, and
 * the anchors (light sockets, equipment slots) are DERIVED from those
 * placements so they can never drift from the geometry. The manifest's
 * collision hint is derived the same way (`collisionBoxesFor`).
 */

