/* ------------------------------------------------------------------- anchors */

/** An assembly's module-local placement (throws on a typo'd assembly id). */
function placementOf(assemblyId: string) {
  const assembly = GALLEY_ASSEMBLIES.find((candidate) => candidate.id === assemblyId)
  if (assembly === undefined) {
    throw new Error(`galley module: no assembly "${assemblyId}"`)
  }
  return assembly.placement
}

/**
 * An equipment anchor AT the assembly's own origin — anchors and geometry
 * share one source, so a moved prop moves its anchor with it.
 */
function equipmentSlot(assemblyId: string): EquipmentSlot {
  const { position, rotation } = placementOf(assemblyId)
  return { id: assemblyId, position: position ?? [0, 0, 0], rotation: rotation ?? 0 }
}

/** A light fixture anchor at an assembly's origin (panel lights, displays). */
function lightSocketOf(assemblyId: string, kind: LightKind): LightSocket {
  const { position, rotation } = placementOf(assemblyId)
  return {
    id: assemblyId,
    kind,
    position: position ?? [0, 0, 0],
    rotation: rotation ?? 0,
  }
}

/**
 * The coffee station's task-light anchor, read off the station's OWN geometry:
 * `coffeeStationParts` hangs its strip light on the cabinet's front face, so
 * the socket is that primitive-local point placed through the same transform
 * the parts went through (placePoint) — the M4-T1 rig lights the real fixture.
 */
function coffeeTaskLight(): LightSocket {
  return {
    id: 'coffee-station-task',
    kind: 'task',
    position: placePoint(COFFEE_STRIP_LOCAL, placementOf('coffee-station')),
  }
}

