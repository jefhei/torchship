/* -------------------------------------------------------------------- cargo */

/**
 * The kit's cargo crate (M2-T5 primitive), at the hold's standard size: a
 * 0.9 × 0.7 × 1.2 m container on 0.06 m skids, lashed by two webbing straps —
 * 0.78 m tall on the deck, which is what the stacks are pitched at.
 */
function crate(): ModuleAssembly['parts'] {
  return cargoCrateParts({
    width: 0.9,
    height: 0.7,
    depth: 1.2,
    skidHeight: 0.06,
    skidThickness: 0.08,
    straps: 2,
    strapWidth: 0.06,
    strapThickness: 0.02,
  })
}

