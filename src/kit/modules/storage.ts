/* ------------------------------------------------------------------- anchors */

/** An assembly's module-local placement (throws on a typo'd assembly id). */
function placementOf(assemblyId: string) {
  const assembly = STORAGE_ASSEMBLIES.find((candidate) => candidate.id === assemblyId)
  if (assembly === undefined) {
    throw new Error(`storage module: no assembly "${assemblyId}"`)
  }
  return assembly.placement
}

/**
 * An equipment anchor AT the assembly's own origin — anchors and geometry
 * share one source, so a moved crate moves its anchor with it.
 */
function equipmentSlot(assemblyId: string): EquipmentSlot {
  const { position, rotation } = placementOf(assemblyId)
  return { id: assemblyId, position: position ?? [0, 0, 0], rotation: rotation ?? 0 }
}

/** A light fixture anchor at an assembly's origin (panel lights, displays). */
function lightSocketOf(assemblyId: string, kind: LightKind): LightSocket {
  const { position, rotation } = placementOf(assemblyId)
  return {
    id: assemblyId,
    kind,
    position: position ?? [0, 0, 0],
    rotation: rotation ?? 0,
  }
}

/** The lens offset inside a panel-light primitive (panelLightParts), meters. */
const PANEL_LENS_LOCAL: Vec3 = [0, -0.03, 0]

/**
 * The loadmaster's task-light anchor, read off the fixture's OWN emissive part:
 * `panelLightParts` puts the lens 0.03 m below the housing centre, so the
 * socket is that primitive-local point placed through the same transform the
 * parts went through (placePoint) — the M4-T1 rig lights the real lens.
 */
function loadmasterTaskLight(): LightSocket {
  return {
    id: 'loadmaster-task-light',
    kind: 'task',
    position: placePoint(PANEL_LENS_LOCAL, placementOf('loadmaster-task-light')),
  }
}

