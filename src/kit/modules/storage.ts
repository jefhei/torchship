/* ---------------------------------------------------------------- assemblies */

/** A recessed panel light at the kit's standard size. */
function panelLight(): ModuleAssembly['parts'] {
  return panelLightParts({
    width: 0.6,
    depth: 0.3,
    housingThickness: 0.06,
    lensInset: 0.08,
  })
}

/** A named stack: one crate on the deck, its twin lashed on top of it. */
function crateStack(id: string, x: number, z: number): ModuleAssembly[] {
  return [
    {
      id: `${id}-lower`,
      parts: crate(),
      placement: { position: [x, 0, z] },
      solid: true,
    },
    {
      id: `${id}-upper`,
      parts: crate(),
      placement: { position: [x, CRATE_PITCH, z] },
      solid: true,
    },
  ]
}

