/**
 * M2-T5 — the authored STORAGE module: the long-haul cargo hold.
 *
 * BUILD_PLAN M2-T5: "…+ storage module (long-haul variant)". The long-haul
 * preset (src/fixtures/longHaul.ts) stretches the corvette with a SECOND aft
 * cargo deck, so this room is the module the stretch is made of: a bare,
 * unglamorous hold that still has to be a place — cargo lashed down, a spares
 * rack, and a loadmaster's station where the manifest is kept.
 *
 * The room is one deck module on the M1-T2 authoring frame — floor at local
 * y = 0, footprint centred on the origin in XZ, the standardized `spine-door`
 * flush in the module's −z face at the standard 1.0 m centre (src/fixtures/
 * layout.ts). It is the deepest room of the kit (6.0 m), which is what makes it
 * read as a hold rather than a cabin.
 *
 * Reading the room from the spine door (aft, −z) toward the bow (+z):
 *  - CARGO CRATES stack two high in four lashed-down stacks — two along the
 *    port wall (aft and amidships) and two along the starboard wall (aft and
 *    forward of the side door) — each crate on its own skids with webbing
 *    tie-downs over the lid and down both ends, so the load reads as secured;
 *  - the centreline stays clear from the spine door to the bow wall: the
 *    walkway, not a crawl, because the hold is where the crew moves freight;
 *  - the SPARES RACK (a two-door locker bank) lines the port wall forward,
 *    opposite the loadmaster's station;
 *  - the LOADMASTER'S STATION fills the bow-starboard corner: a bench with a
 *    terminal display on the bow wall and its own task strip light above it;
 *  - the rest is practical lighting (four ceiling panels) and exposed conduit
 *    routing down the hold.
 *
 * The starboard wall carries the contract's `side-door` socket (M1-T3
 * contractKit) — off-centre along the wall and facing +x — so the wall panel is
 * cut with the bulkhead builder's `door.centerX` (never freehand geometry,
 * BUILD_PLAN rule 8) and the opening is sealed with a socket-centred hatch, the
 * same way the spine door is. Both hatches belong to the room; the M2-T6 spine
 * module supplies the shaft + per-deck sockets and adds NO hatch of its own.
 *
 * Everything is generated by the M2-T1 builders and placed through `placePart`
 * / `placePoint`; `STORAGE_ASSEMBLIES` is the authored truth, and the anchors
 * (light sockets, equipment slots) are DERIVED from those placements so they
 * can never drift from the geometry. The manifest's collision hint is derived
 * the same way (`collisionBoxesFor`).
 */

